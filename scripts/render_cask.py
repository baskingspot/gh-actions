#!/usr/bin/env python3
"""Write a Homebrew cask for one release.

    render_cask.py --repo NAME --tag vX.Y.Z --release-yaml FILE --sums FILE \
        --description TEXT --homepage URL --out FILE

The program's `.github/release.yaml` lists its targets and its binary. The
release's `SHA256SUMS` gives the hash of each tarball. The cask unpacks the
tarball for the user's platform and links the binary. It needs `yq`, and it
fails on anything it does not understand: an unknown target, a missing
checksum, or a description Homebrew would reject.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ORG = "baskingspot"
MARKER = "# Generated by baskingspot/gh-actions, scripts/render_cask.py."
MAX_DESCRIPTION = 79

# A Zig target triple names the OS and the CPU. Anything else is an error, so
# a new target is a decision and not a silent skip.
PLATFORMS = {
    "x86_64-linux": ("linux", "intel"),
    "aarch64-linux": ("linux", "arm"),
    "x86_64-macos": ("macos", "intel"),
    "aarch64-macos": ("macos", "arm"),
}


@dataclass
class Target:
    os: str
    cpu: str
    asset: str


@dataclass
class Program:
    repo: str
    binary: str
    description: str
    homepage: str
    targets: list[Target]
    requires: list[str]


def platform_of(target: str) -> tuple[str, str]:
    """The (os, cpu) of a Zig target such as `x86_64-linux-musl`."""
    key = "-".join(target.split("-")[:2])
    if key not in PLATFORMS:
        raise ValueError(f"no Homebrew platform for the target {target!r}")
    return PLATFORMS[key]


def program_from(
    repo: str, config: dict[str, Any], description: str, homepage: str
) -> Program:
    description = description.strip().rstrip(".")
    if not description or len(description) > MAX_DESCRIPTION:
        raise ValueError(
            f"the repo's About text must be 1 to {MAX_DESCRIPTION} characters for a cask "
            f"description, and it is {len(description)}"
        )
    targets = []
    for entry in config["targets"]:
        os_name, cpu = platform_of(entry["target"])
        targets.append(Target(os_name, cpu, entry["asset"]))
    return Program(
        repo=repo,
        binary=config["binary"],
        description=description,
        homepage=homepage,
        targets=targets,
        requires=list(config.get("requires", [])),
    )


def parse_sums(text: str) -> dict[str, str]:
    """`sha256sum` output as {file name: hash}."""
    sums = {}
    for line in text.splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})\s+\*?(\S+)", line.strip())
        if match:
            sums[match.group(2)] = match.group(1)
    return sums


def render(program: Program, tag: str, sums: dict[str, str]) -> str:
    """The cask for one program at one release. Pure, so it is tested.

    Stanzas follow Homebrew's own order: version, sha256 before url, then the
    descriptive stanzas, then the binary.
    """
    version = tag.removeprefix("v")
    binary = program.binary

    def block(os_name: str) -> list[str]:
        lines: list[str] = []
        # Homebrew orders on_arm before on_intel.
        for target in sorted(
            (t for t in program.targets if t.os == os_name),
            key=lambda t: t.cpu != "arm",
        ):
            file = f"{binary}-{tag}-{target.asset}.tar.gz"
            if file not in sums:
                raise ValueError(f"{program.repo} {tag} has no checksum for {file}")
            folder = f"{binary}-v#{{version}}-{target.asset}"
            lines += [
                f"    on_{target.cpu} do",
                f'      sha256 "{sums[file]}"',
                f'      url "https://github.com/{ORG}/{program.repo}/releases/download/v#{{version}}/{folder}.tar.gz"',
                f'      binary "{folder}/{binary}"',
                "    end",
            ]
        return [f"  on_{os_name} do", *lines, "  end"] if lines else []

    depends = [f'  depends_on formula: "{name}"' for name in program.requires]
    # The on_macos and on_linux blocks are one group: no blank line between.
    platforms = [*block("macos"), *block("linux")]
    platforms = [*platforms, ""] if platforms else []
    body = [
        f"{MARKER} Do not edit.",
        f'cask "{program.repo}" do',
        f'  version "{version}"',
        "",
        *platforms,
        f'  name "{program.repo}"',
        f'  desc "{program.description}"',
        f'  homepage "{program.homepage}"',
        "",
        "  livecheck do",
        "    url :url",
        "    strategy :github_latest",
        "  end",
        "",
        *([*depends, ""] if depends else []),
        "  # The release binaries are not signed or notarized, so macOS quarantines them.",
        "  postflight_steps do",
        "    on_macos do",
        '      run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{staged_path}}"]',
        "    end",
        "  end",
        "end",
        "",
    ]
    return "\n".join(body)


def yaml_to_json(path: Path) -> dict[str, Any]:
    out = subprocess.run(
        ["yq", "-o=json", ".", str(path)], capture_output=True, text=True, check=True
    )
    return json.loads(out.stdout)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", required=True)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--release-yaml", required=True, type=Path)
    parser.add_argument("--sums", required=True, type=Path)
    parser.add_argument("--description", required=True)
    parser.add_argument("--homepage", required=True)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    program = program_from(
        args.repo, yaml_to_json(args.release_yaml), args.description, args.homepage
    )
    cask = render(program, args.tag, parse_sums(args.sums.read_text(encoding="utf-8")))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(cask, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
